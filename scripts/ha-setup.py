#!/usr/bin/env python3
"""Write the Home Assistant files for pollen and events, one set of sensors per person.

    python3 scripts/ha-setup.py --host 192.168.1.10:8010 person.alex person.sam

Writes world_assistant.yaml (copy it to /config/packages/) and pollen.yaml (paste into a dashboard)
into ./ha-out/. Each person gets their own location sensor (the Home Assistant app's position
while they are away, otherwise zone.home) and their own pollen and events sensors, so nobody sees
the pollen count or event list for somewhere else. The dashboards show each viewer their own.
See docs/home-assistant.md. No secrets are written: the API token stays in secrets.yaml.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ALLERGENS = ("alder", "birch", "grasses", "mugwort", "olive", "ragweed")
_PERSON = re.compile(r"^person\.([a-z0-9_]+)$")
_HOST = re.compile(r"^[A-Za-z0-9.\-]+(:[0-9]{1,5})?$")


def slugs(people: list[str]) -> list[str]:
    out = []
    for p in people:
        m = _PERSON.match(p)
        if not m:
            raise ValueError(f"{p!r} is not a person entity id such as person.alex")
        out.append(m.group(1))
    if len(set(out)) != len(out):
        raise ValueError("a person is listed twice")
    if not out:
        raise ValueError("give at least one person, such as person.alex")
    return out


def _away(person: str) -> str:
    """Jinja: true when this person is away with a usable position from the mobile app."""
    return (
        f"{{% set t = states['{person}'] %}}"
        "{% set away = t is not none and t.state not in ['home', 'unknown', 'unavailable']"
        " and t.attributes.latitude is defined and t.attributes.latitude is not none"
        " and t.attributes.longitude is defined"
        " and (t.attributes.gps_accuracy | default(0) | float(0)) <= 1000 %}"
    )


def _allergen(slug: str, name: str) -> str:
    return f"""      - name: WA pollen {slug} {name}
        unique_id: wa_pollen_{slug}_{name}
        state_class: measurement
        state: >-
          {{% set a = state_attr('sensor.wa_pollen_{slug}_allergy_risk', 'allergens') | default([], true)
             | selectattr('name', 'search', '(?i)^{name[:5]}') | list %}}
          {{{{ a[0].levels[0] if a and a[0].levels and a[0].levels[0] is not none else 'unknown' }}}}
"""


def package(people: list[str], host: str, radius_km: int = 8, days: int = 7) -> str:
    if not _HOST.match(host):
        raise ValueError(f"{host!r} should look like 192.168.1.10:8010")
    names = slugs(people)
    head = """# World Assistant for Home Assistant: pollen and events for each person, where they are.
# Generated by scripts/ha-setup.py. Setup is in docs/home-assistant.md:
#   - packages enabled:  under homeassistant: add  packages: !include_dir_named packages
#   - secrets.yaml has:  wa_authorization: "Bearer <contents of api_token.txt>"
# Each person's location is the Home Assistant app's position while they are away from home and it
# reports one (within 1 km), otherwise zone.home. World Assistant stores none of it.

rest:
"""
    rest = ""
    for s in names:
        loc = f"state_attr('sensor.wa_location_{s}', "
        point = (
            f"lat={{{{ {loc}'latitude') or state_attr('zone.home', 'latitude') }}}}"
            f"&lon={{{{ {loc}'longitude') or state_attr('zone.home', 'longitude') }}}}"
        )
        rest += f"""  - resource_template: >-
      http://{host}/v1/pollen/near?{point}
    scan_interval: 3600  # World Assistant caches pollen for hours; no need to ask more often
    timeout: 30
    headers:
      Authorization: !secret wa_authorization
    sensor:
      - name: WA pollen {s} allergy risk
        unique_id: wa_pollen_{s}_allergy_risk
        value_template: "{{{{ value_json.allergy_risk[0] if value_json.allergy_risk else 'unknown' }}}}"
        unit_of_measurement: "/10"
        state_class: measurement
        icon: mdi:flower-pollen
        json_attributes: [dates, allergy_risk, allergy_risk_level, allergy_risk_label, allergens, source]

  - resource_template: >-
      http://{host}/v1/events/near?{point}&radius_km={radius_km}&days={days}&limit=20
    scan_interval: 3600
    timeout: 30
    headers:
      Authorization: !secret wa_authorization
    sensor:
      - name: WA events {s} upcoming
        unique_id: wa_events_{s}_upcoming
        value_template: "{{{{ value_json.count | default(0) }}}}"
        state_class: measurement
        icon: mdi:calendar-star
        json_attributes: [events, days, radius_km, sources]
      - name: WA events {s} next
        unique_id: wa_events_{s}_next
        value_template: "{{{{ value_json.events[0].name if value_json.events else 'Nothing listed' }}}}"
        icon: mdi:ticket
        json_attributes_path: "$.events[0]"
        json_attributes: [date, venue, town, distance_km, price, type]

"""
    tmpl = "template:\n  - sensor:\n"
    for s, person in zip(names, people, strict=True):
        a = _away(person)
        tmpl += f"""      - name: WA location {s}
        unique_id: wa_location_{s}
        icon: mdi:crosshairs-gps
        state: >-
          {a}{{{{ 'phone' if away else 'home zone' }}}}
        attributes:
          latitude: >-
            {a}{{{{ state_attr('{person}', 'latitude') if away else state_attr('zone.home', 'latitude') }}}}
          longitude: >-
            {a}{{{{ state_attr('{person}', 'longitude') if away else state_attr('zone.home', 'longitude') }}}}
"""
        for name in ALLERGENS:
            tmpl += _allergen(s, name)
    return head + rest + tmpl


_VIEWER = (
    "{% set me = states.person | selectattr('name', 'eq', user) | list %}"
    "{% set s = me[0].entity_id.split('.')[1] if me else '' %}"
)


def pollen_dashboard(people: list[str]) -> str:
    names = slugs(people)
    views = f"""title: Pollen
views:
  - title: Pollen
    path: pollen
    icon: mdi:flower-pollen
    cards:
      - type: markdown
        title: Pollen this week
        content: |
          {_VIEWER}
          {{% set r = 'sensor.wa_pollen_' ~ s ~ '_allergy_risk' %}}
          {{% set bars = ['⬜', '🟩', '🟨', '🟧', '🟥'] %}}
          {{% set dates = state_attr(r, 'dates') or [] %}}
          {{% set allergens = state_attr(r, 'allergens') or [] %}}
          {{% if dates %}}Allergy risk where you are, {{{{ user }}}}: **{{{{ (state_attr(r, 'allergy_risk_label') or ['unknown'])[0] or 'unknown' }}}}** ({{{{ states(r) }}}}/10)

          | |{{% for d in dates %}} {{{{ as_datetime(d).strftime('%a') }}}} |{{% endfor %}}
          |:--|{{% for d in dates %}}:-:|{{% endfor %}}{{% for a in allergens %}}
          | **{{{{ a.name }}}}** |{{% for lv in (a.levels or []) %}} {{{{ bars[lv | int(0)] if lv is not none else '▫️' }}}} |{{% endfor %}}{{% endfor %}}

          ⬜ none 🟩 low 🟨 moderate 🟧 high 🟥 very high
          {{% else %}}No pollen data for you yet. Is the World Assistant package installed, and does a person
          named "{{{{ user }}}}" exist? (docs/home-assistant.md){{% endif %}}
"""
    for s in names:
        ents = "".join(
            f"          - entity: sensor.wa_pollen_{s}_{n}\n            name: {n.title()}\n"
            for n in ALLERGENS
        )
        views += f"""  - title: History {s}
    path: history-{s}
    icon: mdi:chart-line
    cards:
      - type: history-graph
        title: Last 30 days, {s}
        hours_to_show: 720
        entities:
          - entity: sensor.wa_pollen_{s}_allergy_risk
            name: Allergy risk
{ents}"""
    return views


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("people", nargs="+", help="person entities, e.g. person.alex person.sam")
    ap.add_argument("--host", required=True, help="World Assistant address and port, e.g. 192.168.1.10:8010")
    ap.add_argument("--radius-km", type=int, default=8, help="how far to look for events (default 8)")
    ap.add_argument("--days", type=int, default=7, help="how many days of events (default 7)")
    ap.add_argument("--out", default="ha-out", help="folder to write to (default ./ha-out)")
    args = ap.parse_args(argv)
    try:
        pkg = package(args.people, args.host, args.radius_km, args.days)
        dash = pollen_dashboard(args.people)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "world_assistant.yaml").write_text(pkg, encoding="utf-8")
    (out / "pollen.yaml").write_text(dash, encoding="utf-8")
    print(f"Wrote {out}/world_assistant.yaml and {out}/pollen.yaml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
